// YouTube Caption Extractor - popup logic
//
// Discover the current video's timed-text tracks in YouTube's player response,
// fetch the selected track, and save it as WebVTT or Markdown.

const statusEl = document.getElementById('status');
const filenameEl = document.getElementById('filename');
const trackEl = document.getElementById('track');
const extractBtn = document.getElementById('extract');

let activeTabId = null;
let discoveredVideoId = null;
let discoveredTracks = [];

function setStatus(text, isError) {
  statusEl.textContent = text;
  statusEl.classList.toggle('error', !!isError);
}

async function runInActiveTab(func, args = []) {
  if (!activeTabId) {
    const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
    activeTabId = tab?.id || null;
  }
  if (!activeTabId) throw new Error('No active tab.');

  let results;
  try {
    results = await chrome.scripting.executeScript({
      target: { tabId: activeTabId },
      world: 'MAIN',
      func,
      args
    });
  } catch (err) {
    throw new Error('Could not run in the YouTube tab: ' + (err?.message || String(err)));
  }

  const framed = results?.find(entry => entry?.error);
  if (framed) {
    const message = framed.error?.message || String(framed.error);
    throw new Error('The YouTube page raised an error: ' + message);
  }
  return results?.find(entry => entry?.result)?.result;
}

// activeTab injects into whatever tab is focused, so the popup checks the tab's
// origin before touching it rather than relying on the manifest's host scope.
function isYouTubeTabUrl(rawUrl) {
  try {
    const url = new URL(rawUrl);
    if (url.protocol !== 'https:') return false;
    return url.hostname === 'youtube.com' ||
      url.hostname.endsWith('.youtube.com') ||
      url.hostname === 'youtube-nocookie.com' ||
      url.hostname.endsWith('.youtube-nocookie.com');
  } catch {
    return false;
  }
}

async function resolveYouTubeTab() {
  const [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  if (!tab?.id) throw new Error('No active tab.');
  if (!isYouTubeTabUrl(tab.url)) {
    throw new Error('Open a YouTube video tab, then click the extension there.');
  }
  activeTabId = tab.id;
  return tab;
}

function sortCaptionTracks(tracks, preferredLanguages) {
  const normalize = language => String(language || '').replace(/_/g, '-').toLowerCase();
  const languages = [...new Set(preferredLanguages.map(normalize).filter(Boolean))];
  const autoLanguages = [...new Set(tracks.filter(track => track.isAutoGenerated)
    .map(track => normalize(track.languageCode).split('-')[0]).filter(Boolean))];
  const originalLanguage = autoLanguages.length === 1 ? autoLanguages[0] : '';
  const rank = track => {
    const language = normalize(track.languageCode);
    const base = language.split('-')[0];
    const preferred = languages.findIndex(candidate => candidate.split('-')[0] === base);
    const languageRank = preferred >= 0 ? preferred :
      originalLanguage && base === originalLanguage.split('-')[0] ? languages.length : languages.length + 1;
    const exactRank = preferred >= 0 && language === languages[preferred] ? 0 : 1;
    return [languageRank, track.isAutoGenerated ? 1 : 0, exactRank];
  };
  return [...tracks].sort((a, b) => {
    const left = rank(a);
    const right = rank(b);
    for (let index = 0; index < left.length; index++) {
      if (left[index] !== right[index]) return left[index] - right[index];
    }
    return 0;
  });
}

async function loadCaptionTracks() {
  try {
    await resolveYouTubeTab();
    const result = await runInActiveTab(discoverCaptionTracks);
    if (result?.error) throw new Error(result.error);
    discoveredVideoId = result.videoId || null;
    const languages = typeof navigator !== 'undefined'
      ? (navigator.languages?.length ? navigator.languages : [navigator.language]) : [];
    discoveredTracks = sortCaptionTracks(result.tracks || [], languages);
    if (!result?.tracks?.length) {
      trackEl.innerHTML = '<option>No published captions - use local Whisper</option>';
      extractBtn.disabled = false;
      setStatus('No published captions. Click Extract for local transcription options.');
      return;
    }

    trackEl.textContent = '';
    for (const track of discoveredTracks) {
      const option = document.createElement('option');
      option.value = String(track.index);
      option.textContent = track.name +
        (track.isAutoGenerated && !/\(auto-generated\)/i.test(track.name) ? ' (auto-generated)' : '');
      trackEl.appendChild(option);
    }
    trackEl.disabled = false;
    trackEl.value = String(discoveredTracks[0].index);
    extractBtn.disabled = false;
    discoveredVideoId = result.videoId || null;
    setStatus(`Found ${result.tracks.length} caption track${result.tracks.length === 1 ? '' : 's'}. ` +
      'Choose the language and version you want to extract.');
  } catch (err) {
    trackEl.innerHTML = '<option>No captions found</option>';
    setStatus(err?.message || String(err), true);
  }
}

extractBtn.addEventListener('click', async () => {
  extractBtn.disabled = true;
  trackEl.disabled = true;
  setStatus('Extracting... keep this popup open.');
  try {
    const format = document.querySelector('input[name="format"]:checked')?.value === 'vtt' ? 'vtt' : 'md';
    const trackIndex = Number.parseInt(trackEl.value, 10);
    const result = await runInActiveTab(extractAndDownload, [
      Number.isFinite(trackIndex) ? trackIndex : 0,
      filenameEl.value.trim() || null,
      format,
      discoveredVideoId,
      discoveredTracks.find(track => track.index === trackIndex) || null
    ]);

    if (result?.canTranscribe) {
      const tab = await chrome.tabs.get(activeTabId);
      await localTranscription.start('youtube', tab, format, filenameEl.value.trim());
      return;
    }
    if (result?.error) throw new Error(result.error);
    if (!result?.cueCount) throw new Error('The selected caption track contained no readable cues.');

    const source = result.source === 'transcript-panel' ? 'published transcript panel' :
      result.isAutoGenerated ? 'auto-generated captions' : 'creator-provided captions';
    const chapterLine = result.format === 'md' && result.chapterCount > 0
      ? `Included ${result.chapterCount} YouTube chapter${result.chapterCount === 1 ? '' : 's'}.\n`
      : '';
    setStatus(
      `Source: YouTube ${source} (${result.trackName}, ${result.languageCode}).\n` +
      chapterLine +
      `Extracted ${result.cueCount} cues (${(result.byteCount / 1024).toFixed(1)} KB).\n` +
      `Saved to Downloads as:\n${result.filename}`
    );
  } catch (err) {
    setStatus('Error: ' + (err?.message || String(err)), true);
  } finally {
    extractBtn.disabled = localTranscription.busy;
    trackEl.disabled = localTranscription.busy || !discoveredTracks.length;
  }
});

trackEl.addEventListener('change', () => {
  setStatus(`Selected: ${trackEl.selectedOptions[0]?.textContent || 'caption track'}.`);
});

loadCaptionTracks().then(() => localTranscription.restore());

// Injected functions must remain self-contained because Chrome serializes them
// into the page's MAIN world.
function discoverCaptionTracks() {
  function getPlayer() {
    return document.getElementById(/^\/shorts\//.test(new URL(location.href).pathname) ? 'shorts-player' : 'movie_player');
  }

  function getPlayerResponse() {
    const player = getPlayer();
    if (typeof player?.getPlayerResponse === 'function') {
      const response = player.getPlayerResponse();
      if (response) return response;
    }
    return window.ytInitialPlayerResponse || null;
  }

  function trackName(track) {
    const name = track?.name;
    if (name?.simpleText) return name.simpleText;
    if (Array.isArray(name?.runs)) return name.runs.map(run => run.text || '').join('');
    return track?.languageCode || 'Unknown';
  }

  const response = getPlayerResponse();
  if (!response) {
    return { error: 'YouTube player data is not ready. Wait for the video to load, then reopen the extension.' };
  }

  const tracks = response.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
  return {
    title: response.videoDetails?.title || document.title.replace(/\s*-\s*YouTube\s*$/i, ''),
    videoId: response.videoDetails?.videoId || null,
    tracks: tracks.map((track, index) => ({
      index,
      name: trackName(track),
      languageCode: track.languageCode || 'und',
      vssId: track.vssId || '',
      isAutoGenerated: track.kind === 'asr'
    }))
  };
}

async function extractAndDownload(trackIndex, suggestedName, format, expectedVideoId, expectedTrack) {
  format = format === 'vtt' ? 'vtt' : 'md';

  function getPlayer() {
    return document.getElementById(/^\/shorts\//.test(new URL(location.href).pathname) ? 'shorts-player' : 'movie_player');
  }

  function getPlayerResponse() {
    const player = getPlayer();
    if (typeof player?.getPlayerResponse === 'function') {
      const response = player.getPlayerResponse();
      if (response) return response;
    }
    return window.ytInitialPlayerResponse || null;
  }

  function trackName(track) {
    const name = track?.name;
    if (name?.simpleText) return name.simpleText;
    if (Array.isArray(name?.runs)) return name.runs.map(run => run.text || '').join('');
    return track?.languageCode || 'Unknown';
  }

  function cleanText(value) {
    return String(value || '')
      .replace(/\u00a0/g, ' ')
      .replace(/\s*\n+\s*/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
  }

  function jsonToCues(json) {
    const cues = [];
    for (const event of json?.events || []) {
      if (!Array.isArray(event?.segs)) continue;
      const text = cleanText(event.segs.map(segment => segment?.utf8 || '').join(''));
      if (!text) continue;
      const startMs = Math.max(0, Number(event.tStartMs) || 0);
      const durationMs = Math.max(0, Number(event.dDurationMs) || 0);
      cues.push({ startMs, endMs: startMs + durationMs, text });
    }
    // fillCueEndTimes reads cues[i+1] as the chronological successor, so JSON3
    // events that arrive out of order would otherwise produce wrong cue ends.
    return cues.sort((a, b) => a.startMs - b.startMs);
  }

  function decodeEntities(value) {
    // Legacy timedtext XML double-escapes, so DOMParser leaves a literal
    // "&#39;" behind. Decode one more level before the VTT writer re-escapes.
    return String(value || '').replace(/&(#\d+|#x[0-9a-fA-F]+|[a-zA-Z]+);/g, (match, entity) => {
      if (entity[0] === '#') {
        const code = entity[1] === 'x' || entity[1] === 'X'
          ? Number.parseInt(entity.slice(2), 16)
          : Number.parseInt(entity.slice(1), 10);
        // String.fromCodePoint throws RangeError outside Unicode range or on a
        // surrogate half; an unguarded call aborts the whole XML fallback.
        const inRange = Number.isFinite(code) && code > 0 && code <= 0x10ffff &&
          !(code >= 0xd800 && code <= 0xdfff);
        return inRange ? String.fromCodePoint(code) : match;
      }
      const named = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
      return Object.prototype.hasOwnProperty.call(named, entity.toLowerCase())
        ? named[entity.toLowerCase()]
        : match;
    });
  }

  function nodeTextWithBreaks(node) {
    // textContent drops <br/> boundaries without substituting whitespace, so
    // "first<br/>second" would export as the corrupt "firstsecond". Walk the
    // children instead and turn each break element into a space.
    if (!node) return '';
    let out = '';
    for (const child of Array.from(node.childNodes || [])) {
      if (child.nodeType === 1) {
        out += String(child.nodeName || '').toLowerCase() === 'br'
          ? ' '
          : nodeTextWithBreaks(child);
      } else {
        out += child.nodeValue || '';
      }
    }
    return out;
  }

  function xmlToCues(xmlText) {
    const doc = new DOMParser().parseFromString(xmlText, 'text/xml');
    // getElementsByTagName rather than querySelector: it is the one lookup every
    // XML DOM implementation provides, so this path stays testable outside a
    // browser instead of being skipped.
    if (doc.getElementsByTagName('parsererror').length) return [];

    // An HTML bot interstitial or soft error page is served with HTTP 200 and
    // parses as well-formed XML, so without a structural check every <p> in it
    // became a cue and the UI reported a successful export. Require a timed-text
    // root, and require each cue node to actually carry a timing attribute.
    const rootName = String(doc.documentElement?.nodeName || '').toLowerCase();
    if (!['timedtext', 'transcript', 'tt'].includes(rootName)) return [];

    const hasTiming = (node, ...names) =>
      names.some(attribute => node.getAttribute(attribute) !== null &&
        node.getAttribute(attribute) !== '');

    const legacy = Array.from(doc.getElementsByTagName('text'))
      .filter(node => hasTiming(node, 'start', 'dur'))
      .map(node => {
        const startMs = Math.max(0, (Number(node.getAttribute('start')) || 0) * 1000);
        const durationMs = Math.max(0, (Number(node.getAttribute('dur')) || 0) * 1000);
        return { startMs, endMs: startMs + durationMs, text: cleanText(decodeEntities(nodeTextWithBreaks(node))) };
      });
    const srv3 = Array.from(doc.getElementsByTagName('p'))
      .filter(node => hasTiming(node, 't', 'd'))
      .map(node => {
        const startMs = Math.max(0, Number(node.getAttribute('t')) || 0);
        const durationMs = Math.max(0, Number(node.getAttribute('d')) || 0);
        return { startMs, endMs: startMs + durationMs, text: cleanText(decodeEntities(nodeTextWithBreaks(node))) };
      });
    // fillCueEndTimes assumes cues[i+1] is the chronological successor, which
    // concatenating two document sections does not guarantee.
    return legacy.concat(srv3)
      .filter(cue => cue.text)
      .sort((a, b) => a.startMs - b.startMs);
  }

  function captionUrlMatchesTrack(rawUrl, track, videoId) {
    try {
      const url = new URL(rawUrl, location.href);
      // A resource-timing entry can come from any origin on the page, so the
      // host is checked here too rather than only at fetch time.
      if (url.protocol !== 'https:' || !isYouTubeCaptionHost(url.hostname)) return false;
      if (!/\/api\/timedtext$/i.test(url.pathname)) return false;
      const urlVideoId = url.searchParams.get('v');
      const languageCode = url.searchParams.get('lang');
      const kind = url.searchParams.get('kind');
      const vssId = url.searchParams.get('vssId') || url.searchParams.get('vss_id');
      const name = url.searchParams.get('name');
      // A missing identifying parameter is not a match: treating it as a
      // wildcard let an unrelated entry win the POT fallback.
      if (!urlVideoId) return false;
      if (videoId && urlVideoId !== videoId) return false;
      if (track.languageCode && languageCode !== track.languageCode) return false;
      // YouTube often omits vssId from the tokenized timed-text URL even when
      // the player-response track carries one. Treat an absent value as
      // unavailable evidence, but reject an explicit mismatch.
      if (track.vssId && vssId && vssId !== track.vssId) return false;
      if (trackName(track) && name !== null && name !== trackName(track)) return false;
      // kind is the auto-generated/manual discriminator, and it is reported back
      // to the user as isAutoGenerated. An absent kind cannot be assumed to
      // match an ASR track, or a manual one would deliver ASR cues labelled
      // manual (and vice versa).
      if ((track.kind === 'asr') !== (kind === 'asr')) return false;
      return true;
    } catch {
      return false;
    }
  }

  async function findRuntimeCaptionUrl(track, videoId) {
    const player = getPlayer();
    if (typeof player?.setOption !== 'function') return null;

    const findResource = (startedAt) => {
      const matches = performance.getEntriesByType('resource')
        .filter(entry => !Number.isFinite(entry.startTime) || entry.startTime >= startedAt)
        .map(entry => entry.name)
        .filter(url => captionUrlMatchesTrack(url, track, videoId))
        .reverse();
      return matches.find(rawUrl => {
        const url = new URL(rawUrl);
        return url.searchParams.has('pot') && url.searchParams.has('c');
      }) || matches.find(url => new URL(url).searchParams.has('pot')) || matches[0] || null;
    };

    let previousTrack;
    let previousTrackRead = false;
    let captionsWereLoaded;
    let trackWasMutated = false;
    try {
      if (typeof performance.setResourceTimingBufferSize === 'function') {
        performance.setResourceTimingBufferSize(1000);
      }
      if (typeof player.getOptions === 'function') {
        const loadedModules = player.getOptions();
        captionsWereLoaded = Array.isArray(loadedModules) && loadedModules.includes('captions');
      }
      if (typeof player.getOption === 'function') {
        try {
          previousTrack = player.getOption('captions', 'track');
          previousTrackRead = true;
        } catch { /* module not loaded */ }
      }
      if (captionsWereLoaded !== true && typeof player.loadModule === 'function') {
        player.loadModule('captions');
      }
      await new Promise(resolve => setTimeout(resolve, 100));

      const playerTracks = typeof player.getOption === 'function'
        ? player.getOption('captions', 'tracklist')
        : [];
      const availableTracks = Array.isArray(playerTracks) ? playerTracks : [];
      const exactPlayerTrack = availableTracks.find(candidate =>
        (candidate?.vssId || candidate?.vss_id) === track.vssId
      );
      const weakPlayerTracks = availableTracks.filter(candidate => {
        const candidateVssId = candidate?.vssId || candidate?.vss_id;
        return (!candidateVssId || !track.vssId) &&
          candidate?.languageCode === track.languageCode &&
          (candidate?.kind === 'asr' || String(candidate?.vssId || '').startsWith('a.')) ===
            (track.kind === 'asr' || String(track.vssId || '').startsWith('a.'));
      });
      const playerTrack = exactPlayerTrack ||
        (weakPlayerTracks.length === 1 ? weakPlayerTracks[0] : null);
      const target = playerTrack || {
        languageCode: track.languageCode,
        kind: track.kind || undefined,
        name: trackName(track)
      };

      // Re-selecting the active track can be a no-op, so briefly clear it to
      // force the player to issue a fresh, tokenized timed-text request.
      player.setOption('captions', 'track', {});
      trackWasMutated = true;
      await new Promise(resolve => setTimeout(resolve, 50));
      const requestStartedAt = performance.now();
      player.setOption('captions', 'track', target);

      for (let attempt = 0; attempt < 40; attempt++) {
        await new Promise(resolve => setTimeout(resolve, 100));
        const runtimeUrl = findResource(requestStartedAt);
        if (runtimeUrl && ((new URL(runtimeUrl).searchParams.has('pot') &&
            new URL(runtimeUrl).searchParams.has('c')) || attempt === 39)) {
          return runtimeUrl;
        }
      }
      return null;
    } catch {
      return null;
    } finally {
      // Restore whatever caption state the viewer had. Every path that mutated
      // the track must undo it, including when the previous track could not be
      // read - otherwise the player is left switched to our pick.
      if (captionsWereLoaded === false && typeof player.unloadModule === 'function') {
        try { player.unloadModule('captions'); } catch { /* best effort */ }
      } else if (previousTrackRead) {
        try { player.setOption('captions', 'track', previousTrack || {}); } catch { /* best effort */ }
      } else if (trackWasMutated) {
        // The prior track was unreadable, so it cannot be restored. Unloading
        // the module leaves the player closer to its untouched state than
        // setOption({}), which pins captions off.
        if (typeof player.unloadModule === 'function') {
          try { player.unloadModule('captions'); } catch { /* best effort */ }
        } else {
          try { player.setOption('captions', 'track', {}); } catch { /* best effort */ }
        }
      }
    }
  }

  function findAudioCaptionUrl(track, videoId) {
    const player = getPlayer();
    if (typeof player?.getAudioTrack !== 'function') return null;
    try {
      const candidates = player.getAudioTrack()?.captionTracks || [];
      const matches = candidates.filter(candidate => {
        const rawUrl = candidate?.url || candidate?.baseUrl;
        const candidateVssId = candidate?.vssId || candidate?.vss_id;
        return rawUrl &&
          (!candidateVssId || !track.vssId || candidateVssId === track.vssId) &&
          captionUrlMatchesTrack(rawUrl, track, videoId);
      });
      const match = matches.find(candidate =>
        (candidate?.vssId || candidate?.vss_id) === track.vssId
      ) || (matches.length === 1 ? matches[0] : null);
      const rawUrl = match?.url || match?.baseUrl;
      return rawUrl && new URL(rawUrl, location.href).searchParams.has('pot') ? rawUrl : null;
    } catch {
      return null;
    }
  }

  function isYouTubeCaptionHost(hostname) {
    return hostname === 'youtube.com' ||
      hostname.endsWith('.youtube.com') ||
      hostname === 'youtube-nocookie.com' ||
      hostname.endsWith('.youtube-nocookie.com');
  }

  async function fetchCaptionTrack(rawUrl) {
    const captionUrl = new URL(rawUrl, location.href);
    // The README and PRIVACY.md both promise YouTube-only network access; this
    // is the check that makes that true in code rather than by convention.
    if (captionUrl.protocol !== 'https:' || !isYouTubeCaptionHost(captionUrl.hostname)) {
      return { ok: false, status: 0, body: '', blocked: true };
    }
    captionUrl.searchParams.set('fmt', 'json3');
    try {
      const response = await fetch(captionUrl.href, { credentials: 'include', signal: AbortSignal.timeout(15000) });
      return {
        ok: response.ok,
        status: response.status,
        body: response.ok ? await response.text() : ''
      };
    } catch (error) {
      return { ok: false, status: 0, body: '', error: 'Caption request failed: ' + error.message };
    }
  }

  async function readTranscriptPanel(track, videoId, durationMs) {
    const panelSelector = 'ytd-engagement-panel-section-list-renderer[target-id="engagement-panel-searchable-transcript"]';
    const rowSelector = 'ytd-transcript-segment-renderer';
    const currentVideo = () => getPlayerResponse()?.videoDetails?.videoId;
    const visible = element => element.getClientRects().length > 0;
    const findPanel = () => Array.from(document.querySelectorAll(panelSelector))
      .find(panel => panel.getAttribute('visibility') === 'ENGAGEMENT_PANEL_VISIBILITY_EXPANDED' && visible(panel));
    if (!videoId || currentVideo() !== videoId) {
      return { error: 'The video changed before transcript-panel extraction.' };
    }
    let panel = findPanel();
    if (!panel) {
      const button = Array.from(document.querySelectorAll('ytd-video-description-transcript-section-renderer button'))
        .find(element => !element.disabled && visible(element));
      if (!button) {
        if (/^\/shorts\//.test(new URL(location.href).pathname)) {
          return { error: 'YouTube did not deliver the selected Short captions, and Shorts has no transcript panel. ' +
            'Open this video in the regular watch page (https://www.youtube.com/watch?v=' + encodeURIComponent(videoId) +
            ') and retry the same transcript. No Whisper job has been started.' };
        }
        return { error: 'Open YouTube\'s Show transcript panel, then click Extract again. ' +
          'Caption downloads failed; this does not mean published captions are absent.' };
      }
      button.click();
    }
    for (let attempt = 0; attempt < 30; attempt++) {
      if (currentVideo() !== videoId) return { error: 'The video changed while loading its transcript.' };
      panel = findPanel();
      if (panel?.querySelector(rowSelector)) break;
      await new Promise(resolve => setTimeout(resolve, 200));
    }
    if (!panel?.querySelector(rowSelector)) {
      return { error: 'YouTube did not load readable transcript rows. Open Show transcript and retry; ' +
        'no audio download or Whisper job has been started.' };
    }
    // The panel has its own language selection, independent of the player CC
    // track. Never label its text as the popup's selected track without evidence.
    const selectedLanguage = () => {
      const footer = panel?.querySelector('ytd-transcript-footer-renderer');
      const menu = footer?.data?.languageMenu?.sortFilterSubMenuRenderer;
      return cleanText(menu?.subMenuItems?.find(item => item.selected)?.title ||
        menu?.title || footer?.querySelector('#label-text')?.textContent || '');
    };
    const wantedLanguage = cleanText(trackName(track));
    if (selectedLanguage() !== wantedLanguage) {
      const footer = panel.querySelector('ytd-transcript-footer-renderer');
      const button = footer?.querySelector('button, [role="button"]');
      if (button && !button.disabled && button.getAttribute('aria-disabled') !== 'true' && visible(button)) {
        button.click();
        let option;
        for (let attempt = 0; attempt < 10 && !option; attempt++) {
          option = Array.from(document.querySelectorAll(
            'ytd-menu-service-item-renderer, [role="menuitemradio"], [role="menuitem"], [role="option"]'
          )).find(element => visible(element) && element.getAttribute('aria-disabled') !== 'true' &&
            cleanText(element.textContent) === wantedLanguage);
          if (!option) await new Promise(resolve => setTimeout(resolve, 100));
        }
        if (option) {
          option.click();
          for (let attempt = 0; attempt < 30; attempt++) {
            await new Promise(resolve => setTimeout(resolve, 200));
            panel = findPanel();
            if (!panel) break;
            if (selectedLanguage() === wantedLanguage && panel.querySelector(rowSelector)) break;
          }
        } else {
          button.click();
        }
      }
    }
    const language = selectedLanguage();
    if (!language || language !== wantedLanguage) {
      return { error: `The transcript panel language (${language || 'unidentified'}) does not match ` +
        `the selected caption track (${trackName(track)}). Choose the same language in both and retry.` };
    }
    if (!panel.querySelector(rowSelector)) {
      return { error: 'YouTube did not load rows for the selected transcript. Reopen its panel and retry.' };
    }
    const search = panel.querySelector('input[type="search"], input#search, input#transcript-search-box-input');
    if (search) {
      if (search.value.trim()) return { error: 'Clear the transcript search before extracting the full transcript.' };
    }
    let scroller = panel.querySelector('#segments-container');
    if (!scroller) {
      scroller = panel.querySelector(rowSelector).parentElement;
      while (scroller && scroller !== panel && scroller.scrollHeight <= scroller.clientHeight) {
        scroller = scroller.parentElement;
      }
    }
    if (!scroller) return { error: 'Could not identify YouTube\'s transcript scroll container.' };
    const originalTop = scroller.scrollTop;
    const seen = new Map();
    let complete = false;
    let stableBottom = 0;
    try {
      scroller.scrollTop = 0;
      for (let attempt = 0; attempt < 200; attempt++) {
        await new Promise(resolve => setTimeout(resolve, 100));
        if (currentVideo() !== videoId || !panel.isConnected || selectedLanguage() !== language) {
          return { error: 'The video or transcript language changed during extraction. Retry on the intended video.' };
        }
        let invalid = false;
        const before = seen.size;
        for (const row of panel.querySelectorAll(rowSelector)) {
          const data = row.data;
          const text = cleanText(row.querySelector('.segment-text')?.textContent ||
            data?.snippet?.runs?.map(run => run.text || '').join('') || data?.snippet?.simpleText);
          let startMs = data?.startMs == null ? NaN : Number(data.startMs);
          if (!Number.isFinite(startMs)) {
            const timestamp = cleanText(row.querySelector('.segment-timestamp')?.textContent);
            if (/^(?:\d+:)?\d{1,2}:[0-5]\d$/.test(timestamp)) {
              startMs = timestamp.split(':').reduce((value, part) => value * 60 + Number(part), 0) * 1000;
            }
          }
          if (!text || !Number.isFinite(startMs) || startMs < 0 ||
              (Number.isFinite(durationMs) && startMs > durationMs)) {
            invalid = true;
            continue;
          }
          const rawEnd = Number(data?.endMs);
          const endMs = Number.isFinite(rawEnd) && rawEnd > startMs ? rawEnd : startMs;
          seen.set(`${startMs}\n${text}`, { startMs, endMs, text });
        }
        if (invalid) return { error: 'Some transcript rows have unreadable text or timestamps. Refusing a partial download.' };
        const bottom = scroller.scrollTop + scroller.clientHeight >= scroller.scrollHeight - 2;
        const loading = panel.querySelector('ytd-continuation-item-renderer, tp-yt-paper-spinner[active]');
        stableBottom = bottom && !loading && before === seen.size ? stableBottom + 1 : 0;
        if (stableBottom >= 3) {
          complete = true;
          break;
        }
        scroller.scrollTop += Math.max(50, scroller.clientHeight * 0.5);
      }
    } finally {
      scroller.scrollTop = originalTop;
    }
    if (!complete || !seen.size) {
      return { error: 'The full transcript did not finish loading. Refusing a partial download; reopen the panel and retry.' };
    }
    const cues = Array.from(seen.values()).sort((a, b) => a.startMs - b.startMs);
    // Scrolling can settle on a truncated/filtered list. Reject obvious
    // previews rather than presenting them as the full published transcript.
    const last = cues[cues.length - 1];
    if (!Number.isFinite(durationMs) || durationMs <= 0 ||
        Math.max(last.startMs, last.endMs) < durationMs * 0.9 - 2000) {
      return { error: 'The transcript panel does not cover the full recording. Refusing a partial download.' };
    }
    for (let index = 0; index < cues.length; index++) {
      const cue = cues[index];
      if (cue.endMs <= cue.startMs) {
        cue.endMs = Math.min(durationMs, cues[index + 1]?.startMs || cue.startMs + 2000);
      }
      cue.endMs = Math.min(cue.endMs, durationMs);
      if (cue.endMs <= cue.startMs) {
        return { error: 'The transcript panel contains invalid cue intervals. Refusing a partial download.' };
      }
    }
    return { cues };
  }

  function fillCueEndTimes(cues) {
    for (let i = 0; i < cues.length; i++) {
      const cue = cues[i];
      if (cue.endMs <= cue.startMs) {
        const nextStart = cues[i + 1]?.startMs;
        cue.endMs = nextStart > cue.startMs ? nextStart : cue.startMs + 2000;
      }
    }
    return cues;
  }

  function vttTime(milliseconds) {
    const total = Math.max(0, Math.round(milliseconds));
    const hours = Math.floor(total / 3600000);
    const minutes = Math.floor((total % 3600000) / 60000);
    const seconds = Math.floor((total % 60000) / 1000);
    const millis = total % 1000;
    return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}:` +
      `${String(seconds).padStart(2, '0')}.${String(millis).padStart(3, '0')}`;
  }

  function shortTime(milliseconds) {
    const totalSeconds = Math.max(0, Math.floor(milliseconds / 1000));
    const hours = Math.floor(totalSeconds / 3600);
    const minutes = Math.floor((totalSeconds % 3600) / 60);
    const seconds = totalSeconds % 60;
    const mm = String(minutes).padStart(2, '0');
    const ss = String(seconds).padStart(2, '0');
    return hours ? `${hours}:${mm}:${ss}` : `${mm}:${ss}`;
  }

  function cuesToVtt(cues) {
    const lines = ['WEBVTT', ''];
    for (const cue of cues) {
      lines.push(
        `${vttTime(cue.startMs)} --> ${vttTime(cue.endMs)}`,
        // Escaping > covers the "-->" cue-terminator case too, since the
        // escaped form "--&gt;" can no longer be read as a terminator.
        cue.text
          .replace(/&/g, '&amp;')
          .replace(/</g, '&lt;')
          .replace(/>/g, '&gt;'),
        ''
      );
    }
    return lines.join('\n');
  }

  function extractChapters(playerResponse, initialData, expectedVideoId) {
    // markersMap is served in the /next response (window.ytInitialData) on real
    // watch pages; the player response does not always carry it. Read both and
    // take whichever supplies DESCRIPTION_CHAPTERS.
    //
    // ytInitialData is a page global that YouTube's SPA navigation may leave
    // pointing at a previously watched video, which would write the wrong
    // video's chapters into the export. The player response is already guarded
    // by video id at the call site, so guard this one the same way.
    const initialDataVideoId =
      initialData?.currentVideoEndpoint?.watchEndpoint?.videoId || null;
    const initialDataUsable = !expectedVideoId || !initialDataVideoId ||
      initialDataVideoId === expectedVideoId;
    const sources = [playerResponse, initialDataUsable ? initialData : null];
    let chapterEntries = [];
    for (const source of sources) {
      const markerMaps = source?.playerOverlays?.playerOverlayRenderer
        ?.decoratedPlayerBarRenderer?.decoratedPlayerBarRenderer?.playerBar
        ?.multiMarkersPlayerBarRenderer?.markersMap || [];
      const found = markerMaps.find(entry => entry?.key === 'DESCRIPTION_CHAPTERS')
        ?.value?.chapters || [];
      if (found.length) { chapterEntries = found; break; }
    }
    return chapterEntries.map(entry => {
      const chapter = entry?.chapterRenderer;
      const title = chapter?.title?.simpleText ||
        chapter?.title?.runs?.map(run => run.text || '').join('') || '';
      return {
        startMs: Math.max(0, Number(chapter?.timeRangeStartMillis) || 0),
        title: cleanText(title)
      };
    }).filter(chapter => chapter.title).sort((a, b) => a.startMs - b.startMs);
  }

  function cuesToMarkdown(cues, title, chapters) {
    // cleanText collapses newlines: an untreated title injects extra Markdown
    // headings into the export.
    const lines = [`# ${cleanText(title) || 'Transcript'}`, ''];
    // A YouTube-supplied chapter title beginning with '#' would otherwise close
    // the heading line with a second heading marker.
    const headingText = (text) => String(text).replace(/^#+\s*/, '');
    let chapterIndex = 0;
    let emitted = 0;
    for (const cue of cues) {
      while (chapterIndex < chapters.length && chapters[chapterIndex].startMs <= cue.startMs) {
        const chapter = chapters[chapterIndex++];
        lines.push(`## [${shortTime(chapter.startMs)}] ${headingText(chapter.title)}`, '');
        emitted++;
      }
      lines.push(`**[${shortTime(cue.startMs)}]** ${cue.text}`, '');
    }
    // Chapters that start after the last cue still belong in the document;
    // without this flush they were dropped while the popup reported them.
    while (chapterIndex < chapters.length) {
      const chapter = chapters[chapterIndex++];
      lines.push(`## [${shortTime(chapter.startMs)}] ${headingText(chapter.title)}`, '');
      emitted++;
    }
    return { markdown: lines.join('\n'), chapterCount: emitted };
  }

  function saveFile(body, baseName, extension, fallbackTitle, transcriptChoice) {
    let filename = baseName || fallbackTitle || 'youtube-captions';
    filename = filename
      .replace(/\s*-\s*YouTube\s*$/i, '')
      .replace(/[\\/:*?"<>|]/g, '_')
      .replace(/\s+/g, ' ')
      .trim() || 'youtube-captions';
    filename = filename.replace(/\.(vtt|md|txt)$/i, '');
    const choice = cleanText(transcriptChoice).replace(/[\\/:*?"<>|\x00-\x1f]/g, '_').replace(/[. ]+$/, '');
    if (choice) filename = filename.slice(0, Math.max(1, 180 - choice.length)) + '-' + choice;
    filename += extension;

    const mime = extension === '.md' ? 'text/markdown' : 'text/vtt';
    const blobUrl = URL.createObjectURL(new Blob([body], { type: `${mime};charset=utf-8` }));
    const anchor = document.createElement('a');
    anchor.href = blobUrl;
    anchor.download = filename;
    document.body.appendChild(anchor);
    anchor.click();
    setTimeout(() => {
      URL.revokeObjectURL(blobUrl);
      anchor.remove();
    }, 1500);
    return filename;
  }

  const response = getPlayerResponse();
  if (!response) return { error: 'YouTube player data is not available.' };

  const currentVideoId = response.videoDetails?.videoId || null;
  if (expectedVideoId && currentVideoId && expectedVideoId !== currentVideoId) {
    return {
      error: 'The tab moved to a different video since the popup opened. Reopen the extension and try again.'
    };
  }

  const tracks = response.captions?.playerCaptionsTracklistRenderer?.captionTracks || [];
  if (expectedTrack && (!tracks[trackIndex] ||
      trackName(tracks[trackIndex]) !== expectedTrack.name ||
      (tracks[trackIndex].languageCode || 'und') !== expectedTrack.languageCode ||
      (tracks[trackIndex].kind === 'asr') !== expectedTrack.isAutoGenerated ||
      (tracks[trackIndex].vssId || '') !== expectedTrack.vssId)) {
    return { error: 'Caption tracks changed since the popup opened. Reopen it and select the intended transcript again.' };
  }
  if (!tracks.length) return { canTranscribe: true, error: 'No published caption tracks.' };
  const track = tracks[trackIndex];
  if (!track?.baseUrl) return { error: 'The selected caption track is no longer available. Reopen the extension and try again.' };

  let captionResponse = await fetchCaptionTrack(track.baseUrl);
  if (!captionResponse.ok || !captionResponse.body.trim()) {
    const videoId = response.videoDetails?.videoId;
    const audioTrackUrl = findAudioCaptionUrl(track, videoId);
    if (audioTrackUrl) captionResponse = await fetchCaptionTrack(audioTrackUrl);
    const runtimeUrl = (!captionResponse.ok || !captionResponse.body.trim())
      ? await findRuntimeCaptionUrl(track, videoId)
      : null;
    if (runtimeUrl) captionResponse = await fetchCaptionTrack(runtimeUrl);
  }
  let panelResult = null;
  if (!captionResponse.blocked && (!captionResponse.ok || !captionResponse.body.trim())) {
    panelResult = await readTranscriptPanel(track, currentVideoId, Number(response.videoDetails?.lengthSeconds) * 1000);
    if (panelResult.error) return { error: (captionResponse.error ? captionResponse.error + ' ' : '') + panelResult.error };
  }
  if (!panelResult && !captionResponse.ok) {
    if (captionResponse.blocked) {
      return { error: 'Refused to fetch a caption URL outside youtube.com.' };
    }
    return { error: `YouTube returned HTTP ${captionResponse.status} for the caption track.` };
  }
  const raw = captionResponse.body;
  let cues = panelResult?.cues || [];
  if (!panelResult) {
    try {
      cues = jsonToCues(JSON.parse(raw));
    } catch {
      cues = xmlToCues(raw);
    }
    if (!cues.length) {
      panelResult = await readTranscriptPanel(track, currentVideoId, Number(response.videoDetails?.lengthSeconds) * 1000);
      if (panelResult.error) return panelResult;
      cues = panelResult.cues;
    }
  }
  if (getPlayerResponse()?.videoDetails?.videoId !== currentVideoId) {
    return { error: 'The video changed during extraction. Reopen the extension and retry.' };
  }
  fillCueEndTimes(cues);
  if (!cues.length) return { error: 'The selected caption track contained no readable cues.' };

  const title = response.videoDetails?.title || document.title.replace(/\s*-\s*YouTube\s*$/i, '');
  const chapters = format === 'md'
    ? extractChapters(response, window.ytInitialData, currentVideoId)
    : [];
  const rendered = format === 'md' ? cuesToMarkdown(cues, title, chapters) : null;
  const payload = rendered ? rendered.markdown : cuesToVtt(cues);
  const extension = format === 'md' ? '.md' : '.vtt';
  const filename = saveFile(payload, suggestedName, extension, title, trackName(track));

  return {
    cueCount: cues.length,
    byteCount: new TextEncoder().encode(payload).length,
    filename,
    format,
    trackName: trackName(track),
    languageCode: track.languageCode || 'und',
    isAutoGenerated: track.kind === 'asr',
    source: panelResult ? 'transcript-panel' : 'caption-track',
    chapterCount: rendered ? rendered.chapterCount : 0
  };
}
